#!/usr/bin/env python3
"""Layer-1 placement: import the UR10 industrial arm into the warehouse_local env.

Generated by orch-l1-asset-placement.

What it does (non-destructive USD composition):
  * Opens a NEW output stage and SUBLAYERS the canonical warehouse_local env,
    so the shared asset-store .usd is never mutated.
  * References the UR10 (ur10.usd) as an override prim on top, grounded at the
    catalog's start_z and laid out per the catalog / skill placement hints.
  * Idempotent: re-running clears the robot prim's references / xform ops and
    re-authors them, so it never stacks duplicate refs.

Asset resolution (from agent_orchestrator/assets/catalog.yaml):
  ur10            -> {ISAAC_NUCLEUS_DIR}/Robots/UniversalRobots/ur10/ur10.usd
                    drive=fixed-base, start_z=0.0
  warehouse_local-> agent_orchestrator/assets/store/environments/warehouse.usd
                    scale=1.0 (meters; no cm rescale needed)

Separation: UR10 has no catalog separation_m. It is a fixed-base arm, so the
isaac-sim-orchestrator rule applies: >= 1.5x reach. UR10 reach ~1.3 m ->
~2.0 m between bases when more than one is placed.

Run under Isaac Lab's python (resolves the Nucleus token + omni asset paths):
  cd <repo> && \
  $ISAAC_LAB_DIR/isaaclab.sh -p \
    "$WORKSPACE_DIR/generated/scene/place_ur10_in_warehouse.py"

Optional overrides:
  --pos X Y           ground XY of the first arm (default 0 0)
  --count N           place N UR10s in a grid (>= ~2 m apart)
  --out PATH          output stage path
"""
import argparse
import os

# --- Isaac app bootstrap (headless; USD authoring only, no GPU stepping) -----
from isaaclab.app import AppLauncher

_parser = argparse.ArgumentParser(description="Place UR10 into warehouse_local.")
_parser.add_argument("--pos", type=float, nargs=2, default=[0.0, 0.0],
                     metavar=("X", "Y"), help="ground XY of first arm (meters)")
_parser.add_argument("--count", type=int, default=1, help="number of UR10s")
_parser.add_argument("--out", type=str, default=None, help="output .usd path")
AppLauncher.add_app_launcher_args(_parser)
args = _parser.parse_args()
args.headless = True
app_launcher = AppLauncher(args)
simulation_app = app_launcher.app

import math
from pxr import Usd, UsdGeom, Gf, Sdf

# --- Resolve the Nucleus token to a concrete URL ----------------------------
try:
    from isaaclab.utils.assets import ISAAC_NUCLEUS_DIR
except ImportError:  # older Isaac Lab module path
    from omni.isaac.lab.utils.assets import ISAAC_NUCLEUS_DIR

# Catalog-authoritative values (do NOT re-derive ground clearance / spacing).
UR10_USD = f"{ISAAC_NUCLEUS_DIR}/Robots/UniversalRobots/ur10/ur10.usd"
START_Z = 0.0           # catalog start_z for ur10 (fixed base sits on the floor)
SEPARATION_M = 2.0      # arm rule: >= 1.5x reach (UR10 reach ~1.3 m)

# warehouse_local: repo-relative entry -> absolute path.
_REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
WAREHOUSE_USD = os.path.join(
    _REPO_ROOT, "agent_orchestrator", "assets", "store", "environments", "warehouse.usd"
)
assert os.path.exists(WAREHOUSE_USD), f"warehouse_local not found: {WAREHOUSE_USD}"

WORKSPACE_DIR = os.environ.get(
    "WORKSPACE_DIR", os.path.join(_REPO_ROOT, "agent_orchestrator", "workspace")
)
OUT_USD = args.out or os.path.join(
    WORKSPACE_DIR, "generated", "scene", "ur10_in_warehouse.usd"
)
os.makedirs(os.path.dirname(OUT_USD), exist_ok=True)


def author() -> list:
    # Fresh root layer that composes the warehouse as a sublayer (env untouched).
    if os.path.exists(OUT_USD):
        stage = Usd.Stage.Open(OUT_USD)
    else:
        stage = Usd.Stage.CreateNew(OUT_USD)

    root = stage.GetRootLayer()
    # Isaac convention: Z-up, meters. warehouse_local is scale=1.0 (meters).
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)

    wh_ref = WAREHOUSE_USD.replace("\\", "/")
    if wh_ref not in root.subLayerPaths:
        root.subLayerPaths.append(wh_ref)

    # Ensure /World exists (it comes from the warehouse sublayer) + a Robots scope.
    stage.OverridePrim("/World")
    robots_scope = "/World/Robots"
    if not stage.GetPrimAtPath(robots_scope):
        UsdGeom.Scope.Define(stage, robots_scope)

    cols = max(1, math.ceil(math.sqrt(args.count)))
    placed = []
    for i in range(args.count):
        row, col = divmod(i, cols)
        x = args.pos[0] + col * SEPARATION_M
        y = args.pos[1] + row * SEPARATION_M

        prim_path = f"{robots_scope}/UR10_{i}"
        prim = stage.OverridePrim(prim_path)

        # Idempotent: drop any prior reference before (re)adding exactly one.
        prim.GetReferences().ClearReferences()
        prim.GetReferences().AddReference(UR10_USD)
        # ur10.usd already carries ArticulationRootAPI on its base -> do NOT re-apply.

        # T * R * S. start_z = 0.0: the fixed base rests on the warehouse floor.
        xform = UsdGeom.Xformable(prim)
        xform.ClearXformOpOrder()
        xform.AddTranslateOp().Set(Gf.Vec3d(float(x), float(y), START_Z))
        xform.AddOrientOp().Set(Gf.Quatf(1.0, 0.0, 0.0, 0.0))  # identity
        xform.AddScaleOp().Set(Gf.Vec3f(1.0, 1.0, 1.0))        # robot in meters

        placed.append(prim_path)
        print(f"[place] {prim_path}  <-  {UR10_USD}  @ ({x:.2f}, {y:.2f}, {START_Z})")

    stage.GetRootLayer().Save()
    print(f"[save]  {OUT_USD}")
    return placed


placed = author()
print("PLACED_PRIMS=" + ",".join(placed))
print("STAGE=" + OUT_USD)

simulation_app.close()
